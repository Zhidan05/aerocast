-- Allow read for UI, but DO NOT allow unrestricted insert/update.
-- Write operations should eventually be handled server-side (using service_role)
-- or restricted to authenticated users when auth is added.
CREATE POLICY "Allow public read access to simulations" 
ON public.simulations FOR SELECT USING (true);

CREATE POLICY "Allow public read access to simulation_buckets" 
ON public.simulation_buckets FOR SELECT USING (true);

CREATE POLICY "Allow public read access to simulation_samples" 
ON public.simulation_samples FOR SELECT USING (true);

CREATE POLICY "Allow public read access to accuracy_tests" 
ON public.accuracy_tests FOR SELECT USING (true);

