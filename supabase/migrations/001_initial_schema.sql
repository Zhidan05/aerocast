ALTER TABLE public.flight_prices ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.simulations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.simulation_buckets ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.simulation_samples ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.accuracy_tests ENABLE ROW LEVEL SECURITY;

